    pub fn compute_i_cal(&self, _p: &Pharmaco, _ach_block: f64, _c_sev_93: f64) -> f64 { self.a[72] }
    pub fn compute_i_kr(&self, _p: &Pharmaco) -> f64 { self.a[76] }
